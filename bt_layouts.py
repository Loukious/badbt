# Pre-compiled layout cache: char -> [(scancode, [modifier_array]), ...]
_compiled_layouts = {}


def _compile_layout(lang):
    """Compile raw layout data into usable format with modifier arrays."""
    if lang not in _LAYOUT_DATA:
        return None

    raw = _LAYOUT_DATA[lang]
    compiled = {}

    for char, entry in raw.items():
        if isinstance(entry, list):
            # Dead key sequence: list of (scancode, mod_byte) tuples
            compiled[char] = [(sc, _mod_byte_to_array(mb)) for sc, mb in entry]
        else:
            # Single keypress: (scancode, mod_byte) tuple
            sc, mb = entry
            compiled[char] = [(sc, _mod_byte_to_array(mb))]

    # Always include newline/enter and tab if not already present
    if '\n' not in compiled:
        compiled['\n'] = [(40, [0, 0, 0, 0, 0, 0, 0, 0])]
    if '\r' not in compiled:
        compiled['\r'] = [(40, [0, 0, 0, 0, 0, 0, 0, 0])]
    if '\t' not in compiled:
        compiled['\t'] = [(43, [0, 0, 0, 0, 0, 0, 0, 0])]

    return compiled


def get_layout(lang='us'):
    """Get the compiled character mapping for a keyboard layout.

    Args:
        lang: Layout code (e.g., 'us', 'fr', 'de', 'es', 'gb', etc.)

    Returns:
        dict mapping char -> [(scancode, [modifier_array]), ...]
        where modifier_array is [RGUI, RALT, RSHIFT, RCTRL, LGUI, LALT, LSHIFT, LCTRL]

    Falls back to 'us' layout for unsupported languages.
    """
    # Resolve aliases
    lang = _ALIASES.get(lang, lang)

    if lang in _compiled_layouts:
        return _compiled_layouts[lang]

    compiled = _compile_layout(lang)
    if compiled is None:
        # Fall back to US
        if 'us' not in _compiled_layouts:
            _compiled_layouts['us'] = _compile_layout('us')
        return _compiled_layouts['us']

    _compiled_layouts[lang] = compiled
    return compiled


def get_char_keystrokes(char, lang='us'):
    """Get the keystrokes needed to type a single character.

    Args:
        char: The character to type
        lang: Keyboard layout code

    Returns:
        List of (scancode, [modifier_array]) tuples, or None if unsupported.
    """
    layout = get_layout(lang)
    return layout.get(char)
