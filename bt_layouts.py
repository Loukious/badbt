def _mod_byte_to_array(mb):
    """Convert a modifier byte to the 8-element array used by BadBT.
    Array format: [RGUI, RALT, RSHIFT, RCTRL, LGUI, LALT, LSHIFT, LCTRL]
    """
    return [
        (mb >> 7) & 1,  # RGUI
        (mb >> 6) & 1,  # RALT (AltGr)
        (mb >> 5) & 1,  # RSHIFT
        (mb >> 4) & 1,  # RCTRL
        (mb >> 3) & 1,  # LGUI
        (mb >> 2) & 1,  # LALT
        (mb >> 1) & 1,  # LSHIFT
        mb & 1,         # LCTRL
    ]


